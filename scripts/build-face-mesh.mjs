// Generates components/sections/projects/faceMeshData.ts from scripts/data/canonical_face_model.obj
// (MediaPipe canonical face model, Apache-2.0 — see scripts/data/NOTICE.md).
// Run: node scripts/build-face-mesh.mjs
import fs from "node:fs"
import path from "node:path"

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, "$1")), "..")
const SRC = path.join(ROOT, "scripts", "data", "canonical_face_model.obj")
const OUT = path.join(ROOT, "components", "sections", "projects", "faceMeshData.ts")

const verts = []
const edges = new Set()
for (const line of fs.readFileSync(SRC, "utf8").split(/\r?\n/)) {
	const parts = line.trim().split(/\s+/)
	if (parts[0] === "v") verts.push(parts.slice(1, 4).map(Number))
	if (parts[0] === "f") {
		const idx = parts.slice(1).map((p) => Number(p.split("/")[0]) - 1)
		for (let i = 0; i < idx.length; i++) {
			const a = idx[i]
			const b = idx[(i + 1) % idx.length]
			edges.add(a < b ? `${a},${b}` : `${b},${a}`)
		}
	}
}

// Centre on the bounding box and scale so the face spans y ∈ [-1, 1].
const min = [0, 1, 2].map((k) => Math.min(...verts.map((v) => v[k])))
const max = [0, 1, 2].map((k) => Math.max(...verts.map((v) => v[k])))
const centre = min.map((m, k) => (m + max[k]) / 2)
const scale = 2 / (max[1] - min[1])
const flat = verts.flatMap((v) => v.map((c, k) => Math.round((c - centre[k]) * scale * 1000) / 1000))
const edgeList = [...edges].flatMap((e) => e.split(",").map(Number))

// Standard MediaPipe face-mesh landmark groups.
const GROUPS = {
	lips: [61, 146, 91, 181, 84, 17, 314, 405, 321, 375, 291, 409, 270, 269, 267, 0, 37, 39, 40, 185, 78, 95, 88, 178, 87, 14, 317, 402, 318, 324, 308, 415, 310, 311, 312, 13, 82, 81, 80, 191],
	eyes: [263, 249, 390, 373, 374, 380, 381, 382, 362, 398, 384, 385, 386, 387, 388, 466, 33, 7, 163, 144, 145, 153, 154, 155, 133, 173, 157, 158, 159, 160, 161, 246],
	brows: [276, 283, 282, 295, 285, 300, 293, 334, 296, 336, 46, 53, 52, 65, 55, 70, 63, 105, 66, 107],
	oval: [10, 338, 297, 332, 284, 251, 389, 356, 454, 323, 361, 288, 397, 365, 379, 378, 400, 377, 152, 148, 176, 149, 150, 136, 172, 58, 132, 93, 234, 127, 162, 21, 54, 103, 67, 109]
}

const out = `// Generated by scripts/build-face-mesh.mjs — do not edit by hand.
// MediaPipe canonical face model (468 landmarks), Copyright Google LLC, Apache-2.0.
// Coordinates are normalised: x right, y up, z towards the viewer; the face spans y ∈ [-1, 1].

export const FACE_VERTICES = new Float32Array(${JSON.stringify(flat)})

/** Pairs of vertex indices. */
export const FACE_EDGES = new Uint16Array(${JSON.stringify(edgeList)})

export const FACE_GROUPS = ${JSON.stringify(GROUPS)} as const
`
fs.writeFileSync(OUT, out)
console.log(`wrote ${path.relative(ROOT, OUT)}: ${verts.length} vertices, ${edges.size} edges, ${(out.length / 1024).toFixed(1)} KB`)
